create table if not exists public.media_transcriptions (
  id bigint generated by default as identity primary key,
  file_name text not null,
  type text not null,
  transcription text,
  description text,
  status text not null default 'transcribed',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists media_transcriptions_type_idx
  on public.media_transcriptions (type);

create index if not exists media_transcriptions_status_idx
  on public.media_transcriptions (status);

create index if not exists media_transcriptions_file_name_idx
  on public.media_transcriptions (file_name);

create table if not exists public.media_sources (
  id bigint generated by default as identity primary key,
  media_transcription_id bigint references public.media_transcriptions (id) on delete cascade,
  platform text not null default 'youtube',
  external_id text,
  source_url text,
  title text,
  published_at timestamptz,
  duration_seconds integer,
  ayah_start integer,
  ayah_end integer,
  part_label text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (platform, external_id)
);

create index if not exists media_sources_ayah_idx
  on public.media_sources (ayah_start, ayah_end);

alter table public.media_transcriptions enable row level security;
alter table public.media_sources enable row level security;

create policy "local read media transcriptions"
  on public.media_transcriptions for select to anon, authenticated using (true);

create policy "local read media sources"
  on public.media_sources for select to anon, authenticated using (true);
